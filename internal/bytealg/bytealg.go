// Package bytealg provides bounded byte kernels shared by protocol parsers.
package bytealg

// Mask XORs a whole-vector prefix with the four little-endian bytes of key.
// It returns the number of bytes processed; the caller handles the tail.
func Mask(b []byte, key uint32) int {
	if Available && len(b) >= 64 {
		return maskVector(b, key)
	}
	return 0
}

// ValidHeaderValue accepts HTAB, visible ASCII and obs-text, excluding DEL.
func ValidHeaderValue(b []byte) bool {
	if Available && len(b) >= 64 {
		return headerVector(b)
	}
	return validHeaderScalar(b)
}

func validHeaderScalar(b []byte) bool {
	for _, c := range b {
		if headerValueAllowed[c] == 0 {
			return false
		}
	}
	return true
}

